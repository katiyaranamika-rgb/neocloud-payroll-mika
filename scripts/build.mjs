// Zero-dependency build: TypeScript → one browser bundle, plus static files.
//
//   node scripts/build.mjs        → dist/
//
// 1. Strips TypeScript types with Node's built-in module.stripTypeScriptTypes (Node ≥ 22.13).
// 2. Bundles the ES modules under src/ into dist/app.bundle.js. Each module is wrapped in a
//    function scope; its named exports are returned and imported by name — enough for this
//    codebase (relative imports only, no default exports, no cycles).
// 3. Copies public/ and data/ (CSVs stay downloadable at /data/*.csv) and embeds the data in
//    dist/data.bundle.js so the page can also run as a single offline file (dist/standalone.html).

import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const ENTRY = join(ROOT, 'src/ui/app.ts');

try { rmSync(DIST, { recursive: true, force: true }); } catch { /* some mounted folders forbid deletes; files are overwritten below */ }
mkdirSync(DIST, { recursive: true });

// ---- bundle ----
const modules = new Map(); // abs path → { id, code, deps, exports }
const order = [];
const visiting = new Set();
const idFor = p => '__m_' + relative(join(ROOT, 'src'), p).replace(/[^a-zA-Z0-9]/g, '_');

function load(file) {
  if (modules.has(file)) return;
  if (visiting.has(file)) throw new Error(`Import cycle at ${relative(ROOT, file)}`);
  visiting.add(file);
  const src = readFileSync(file, 'utf8');
  let js = stripTypeScriptTypes(src, { mode: 'strip' });
  const deps = [];
  // import { a, b as c } from './x.ts';   (type-only imports were removed by stripping)
  js = js.replace(/^\s*import\s*\{([^}]*)\}\s*from\s*['"](\.[^'"]+)['"];?/gm, (_m, names, spec) => {
    const dep = resolve(dirname(file), spec);
    deps.push(dep);
    const bindings = names.split(',').map(s => s.trim()).filter(Boolean).map(s => s.replace(/\s+as\s+/, ': '));
    return `const { ${bindings.join(', ')} } = ${idFor(dep)};`;
  });
  // export { a, b } from './x.ts';
  const reexports = [];
  js = js.replace(/^\s*export\s*\{([^}]*)\}\s*from\s*['"](\.[^'"]+)['"];?/gm, (_m, names, spec) => {
    const dep = resolve(dirname(file), spec);
    deps.push(dep);
    const ns = names.split(',').map(s => s.trim()).filter(Boolean);
    reexports.push(...ns);
    return `const { ${ns.join(', ')} } = ${idFor(dep)};`;
  });
  if (/^\s*import\s/m.test(js)) throw new Error(`Unsupported import form in ${relative(ROOT, file)}`);
  const exports = [...reexports];
  js = js.replace(/^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z0-9_$]+)/gm, (_m, kw, name) => { exports.push(name); return `${kw} ${name}`; });
  if (/^export\s/m.test(js)) throw new Error(`Unsupported export form in ${relative(ROOT, file)}`);
  for (const d of deps) load(d);
  visiting.delete(file);
  modules.set(file, { id: idFor(file), code: js, exports });
  order.push(file);
}
load(ENTRY);
const bundle = [
  '/* NeoCloud Payroll – generated by scripts/build.mjs. Source: src/ (TypeScript). */',
  '"use strict";',
  ...order.map(f => {
    const m = modules.get(f);
    return `// ---- ${relative(ROOT, f)} ----\nconst ${m.id} = (() => {\n${m.code}\nreturn { ${m.exports.join(', ')} };\n})();`;
  }),
].join('\n');
writeFileSync(join(DIST, 'app.bundle.js'), bundle);

// ---- static files and data ----
// Plain file copy (fs.cpSync preserves modes, which some mounted folders reject).
function copyDir(src, dest) {
  mkdirSync(dest, { recursive: true });
  for (const f of readdirSync(src)) {
    const s = join(src, f); const d = join(dest, f);
    if (statSync(s).isDirectory()) copyDir(s, d); else writeFileSync(d, readFileSync(s));
  }
}
copyDir(join(ROOT, 'public'), DIST);
copyDir(join(ROOT, 'data'), join(DIST, 'data'));
const data = {};
for (const f of readdirSync(join(ROOT, 'data'))) {
  if (f.endsWith('.csv')) data[f.replace(/\.csv$/, '')] = readFileSync(join(ROOT, 'data', f), 'utf8');
}
data.rules = readFileSync(join(ROOT, 'data/rules.json'), 'utf8');
const dataJs = `window.__NEOCLOUD_DATA__ = ${JSON.stringify(data)};\n`;
writeFileSync(join(DIST, 'data.bundle.js'), dataJs);

// ---- single-file offline copy (used for previews and as a downloadable artifact) ----
const html = readFileSync(join(ROOT, 'public/index.html'), 'utf8');
const css = readFileSync(join(ROOT, 'public/styles.css'), 'utf8');
const standalone = html
  .replace('<link rel="stylesheet" href="styles.css">', () => `<style>\n${css}\n</style>`)
  .replace('<script src="data.bundle.js"></script>', () => `<script>\n${dataJs.replace(/<\/script/gi, '<\\/script')}</script>`)
  .replace('<script src="app.bundle.js"></script>', () => `<script>\n${bundle.replace(/<\/script/gi, '<\\/script')}\n</script>`);
writeFileSync(join(DIST, 'standalone.html'), standalone);

const kb = f => (readFileSync(join(DIST, f)).length / 1024).toFixed(0) + ' KB';
console.log(`Built ${order.length} modules → dist/app.bundle.js (${kb('app.bundle.js')}), data.bundle.js (${kb('data.bundle.js')}), standalone.html (${kb('standalone.html')})`);
if (!existsSync(join(DIST, 'index.html'))) throw new Error('public/index.html missing');
